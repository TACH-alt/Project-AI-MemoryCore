import os
import sys
import json
import httpx
import argparse
from datetime import datetime
import uuid

# CONFIGURATION
ROUTER_URL = "http://10.10.10.2:20128/v1"
STATE_FILE = r"C:\Users\Legend\Documents\Claude\Projects\MemoryCore\orchestration\state\orchestration-state.json"
OBSIDIAN_VAULT = r"C:\Users\Legend\Desktop\Obsidian\Legendary"

def load_state():
    if os.path.exists(STATE_FILE):
        try:
            with open(STATE_FILE, 'r', encoding='utf-8') as f:
                return json.load(f)
        except Exception as e:
            print(f"[ERROR] Failed to load state: {e}")
    return {
        "session_id": str(uuid.uuid4()),
        "last_5_messages": [],
        "active_agent": "None",
        "last_model_used": "None"
    }

def save_state(state):
    try:
        with open(STATE_FILE, 'w', encoding='utf-8') as f:
            json.dump(state, f, indent=4)
    except Exception as e:
        print(f"[ERROR] Failed to save state: {e}")

def call_9router(prompt, agent, history):
    # Map agent to model
    model_map = {
        "Legend": "gemini-2.0-flash",
        "Codex": "gpt-4o"
    }
    model = model_map.get(agent, "gpt-4o")
    
    messages = history + [{"role": "user", "content": prompt}]
    
    payload = {
        "model": model,
        "messages": messages,
        "stream": False
    }
    
    try:
        with httpx.Client(timeout=60.0) as client:
            response = client.post(f"{ROUTER_URL}/chat/completions", json=payload)
            response.raise_for_status()
            result = response.json()
            answer = result['choices'][0]['message']['content']
            return answer, model
    except httpx.ConnectError:
        print("[ERROR] 9Router is OFFLINE at http://localhost:20128")
        sys.exit(1)
    except Exception as e:
        print(f"[ERROR] API call failed: {e}")
        sys.exit(1)

def log_to_obsidian(prompt, answer, agent, model, title, folder):
    today = datetime.now().strftime("%Y-%m-%d")
    timestamp = datetime.now().strftime("%H:%M")
    filename = f"{today}-{title}.md"
    target_dir = os.path.join(OBSIDIAN_VAULT, folder)
    
    if not os.path.exists(target_dir):
        os.makedirs(target_dir)
    
    filepath = os.path.join(target_dir, filename)
    
    frontmatter = f"""---
date: {today}
time: {timestamp}
agent: {agent}
model: {model}
title: {title}
tags: [orchestration, {agent.lower()}]
---

"""
    content = f"""# {title}

**Prompt:** {prompt}

---

{answer}

---
*Generated by {agent} via 9Router*
"""
    
    try:
        with open(filepath, 'w', encoding='utf-8') as f:
            f.write(frontmatter + content)
        print(f"[SUCCESS] Result saved to: {filepath}")
    except Exception as e:
        print(f"[ERROR] Failed to save to Obsidian: {e}")

def main():
    parser = argparse.ArgumentParser(description="Legendary Orchestration Worker")
    parser.add_argument("--prompt", required=True, help="The prompt to send")
    parser.add_argument("--agent", required=True, choices=["Legend", "Codex"], help="Agent to use")
    parser.add_argument("--title", default="worker-output", help="Output title")
    parser.add_argument("--folder", default="02-Gemini-Outputs", help="Obsidian folder")
    
    args = parser.parse_args()
    
    state = load_state()
    
    print(f"[{args.agent}] Processing: {args.title}...")
    
    answer, model = call_9router(args.prompt, args.agent, state["last_5_messages"])
    
    # Update state
    state["active_agent"] = args.agent
    state["last_model_used"] = model
    state["last_5_messages"].append({"role": "user", "content": args.prompt})
    state["last_5_messages"].append({"role": "assistant", "content": answer})
    state["last_5_messages"] = state["last_5_messages"][-5:] # Keep last 5 messages as requested
    
    save_state(state)
    
    log_to_obsidian(args.prompt, answer, args.agent, model, args.title, args.folder)

if __name__ == "__main__":
    main()
