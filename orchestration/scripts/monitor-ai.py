def get_active_processes():
    try:
        output = subprocess.check_output("tasklist /FI \"STATUS eq RUNNING\"", shell=True).decode()
        active = []
        for name in AI_PROCESS_NAMES:
            if name.lower() in output.lower():
                active.append(name)
        return active
    except:
        return []

def get_recent_files(directory, limit=8):
    files = []
    for root, _, filenames in os.walk(directory):
        for f in filenames:
            if f.endswith(".md") and ".obsidian" not in root:
                path = os.path.join(root, f)
                files.append((path, os.path.getmtime(path)))
    files.sort(key=lambda x: x[1], reverse=True)
    return files[:limit]

def read_current_session():
    try:
        with open(MEMORY_CORE_SESSION, 'r') as f:
            lines = f.readlines()
            for line in lines:
                if "**Current Session**:" in line:
                    return line.split(":", 1)[1].strip()
    except:
        return "Idle"
    return "Idle"

def read_orchestration_state():
    if os.path.exists(STATE_FILE):
        try:
            with open(STATE_FILE, 'r', encoding='utf-8') as f:
                return json.load(f)
        except:
            pass
    return {"active_agent": "None", "last_model_used": "None"}

def check_9router():
    try:
        with httpx.Client(timeout=1.0) as client:
            response = client.get(f"{ROUTER_URL}/models")
            return response.status_code == 200
    except:
        return False

